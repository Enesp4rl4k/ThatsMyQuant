using System;
using System.Collections.Generic;

namespace ThatsMyQuant.Application.Strategy;

/// <summary>
/// Fractional differentiation in the sense of Lopez de Prado (2018), "Advances in
/// Financial Machine Learning", Chapter 5. Produces a stationary transform of a
/// price series that preserves a maximum amount of memory, in contrast to standard
/// integer differencing (returns) which destroys memory entirely.
///
/// Why this matters:
///   ML models trained on raw prices fail because the input is non-stationary
///   (drift, regime shifts). Returns are stationary but discard the level
///   information that often carries the predictive content. Fractional
///   differencing of order d ∈ (0, 1) produces a stationary series that retains
///   long-range dependence — feature engineering's "best of both worlds."
///
///   Used in the upgrade plan: Phase F (ML composite — XGBoost feature pipeline)
///   and Phase D2 (CVD divergence detection on fractionally differenced cumulative
///   volume delta).
///
/// Method (fixed-window):
///   X̃_t^(d) = Σ_{k=0}^{K-1} ω_k · X_{t-k}
///
///   Weights generated by the recurrence:
///     ω_0 = 1
///     ω_k = -ω_{k-1} · (d - k + 1) / k
///
///   K is chosen as the smallest k such that |ω_k| &lt; tolerance (default 1e-5).
///   The fixed-window form, unlike the expanding window, has constant memory and
///   does not accumulate weight from the distant past — preferred for live use.
///
///   Choose d by binary search on a grid: smallest d for which the differenced
///   series passes a stationarity test (ADF with t-stat &lt; critical value).
///   Implementations typically settle on d ∈ [0.3, 0.6] for crypto price logs.
/// </summary>
public static class FractionalDifferentiation
{
    private const double DefaultTolerance = 1e-5;
    private const int MaxWeightLength = 5_000;

    /// <summary>
    /// Compute fractional-differencing weights via the recurrence
    ///   ω_0 = 1, ω_k = -ω_{k-1} · (d − k + 1) / k.
    /// Truncated at the first k where |ω_k| &lt; tolerance OR k reaches MaxWeightLength.
    /// </summary>
    /// <param name="d">Differencing order, must be in [0, 1].</param>
    /// <param name="tolerance">Truncation threshold on |ω_k|.</param>
    /// <returns>Weights ordered ω_0, ω_1, ω_2, ... — applied as
    /// Σ ω_k · x_{t-k}, so ω_0 multiplies the most recent observation.</returns>
    public static double[] ComputeWeights(double d, double tolerance = DefaultTolerance)
    {
        if (d < 0.0 || d > 1.0)
            throw new ArgumentOutOfRangeException(nameof(d), "Order d must be in [0, 1].");
        if (tolerance <= 0.0)
            throw new ArgumentOutOfRangeException(nameof(tolerance), "Tolerance must be positive.");

        var weights = new List<double> { 1.0 };
        double w = 1.0;
        for (int k = 1; k < MaxWeightLength; k++)
        {
            w = -w * (d - k + 1) / k;
            if (Math.Abs(w) < tolerance) break;
            weights.Add(w);
        }
        return weights.ToArray();
    }

    /// <summary>
    /// Apply the fixed-window fractional-difference operator to a series.
    /// Output[i] = Σ_{k=0}^{K-1} ω_k · series[i-k] for i ≥ K-1.
    /// Output[i] = NaN for i &lt; K-1 (insufficient lookback).
    /// </summary>
    /// <param name="series">Input series (typically log prices for non-stationarity).</param>
    /// <param name="weights">Weights from <see cref="ComputeWeights"/>.</param>
    public static double[] ApplyFixedWindow(IReadOnlyList<double> series, double[] weights)
    {
        ArgumentNullException.ThrowIfNull(series);
        ArgumentNullException.ThrowIfNull(weights);
        if (weights.Length == 0)
            throw new ArgumentException("Weights array must be non-empty.", nameof(weights));

        int n = series.Count;
        int k = weights.Length;
        var output = new double[n];
        for (int i = 0; i < n; i++)
        {
            if (i < k - 1)
            {
                output[i] = double.NaN;
                continue;
            }

            double sum = 0.0;
            for (int j = 0; j < k; j++)
            {
                sum += weights[j] * series[i - j];
            }
            output[i] = sum;
        }
        return output;
    }

    /// <summary>
    /// Convenience: compute weights and apply in one call.
    /// </summary>
    public static double[] Difference(IReadOnlyList<double> series, double d, double tolerance = DefaultTolerance)
    {
        var weights = ComputeWeights(d, tolerance);
        return ApplyFixedWindow(series, weights);
    }

    /// <summary>
    /// Find the minimum differencing order d ∈ [dMin, dMax] such that the
    /// fractionally-differenced series passes a basic stationarity check
    /// (variance bounded vs naïve expansion). Uses a binary search over a fine grid.
    ///
    /// Note: this is a lightweight stationarity proxy (variance ratio test).
    /// For rigorous ADF testing use <see cref="EngleGrangerDetector"/> on the
    /// resulting series; this method is meant for offline ML feature pipelines
    /// where speed matters more than statistical rigor.
    /// </summary>
    /// <param name="series">Input series.</param>
    /// <param name="dMin">Lower bound of search.</param>
    /// <param name="dMax">Upper bound.</param>
    /// <param name="gridSize">Number of grid points.</param>
    /// <param name="varianceRatioCeiling">
    /// Acceptable upper bound on Var(diff_d) / Var(diff_dMax). The minimum d
    /// passing this gate is returned.
    /// </param>
    public static double FindMinimumOrder(
        IReadOnlyList<double> series,
        double dMin = 0.0,
        double dMax = 1.0,
        int gridSize = 21,
        double varianceRatioCeiling = 4.0)
    {
        ArgumentNullException.ThrowIfNull(series);
        if (dMin < 0.0 || dMax > 1.0 || dMin >= dMax)
            throw new ArgumentException("Require 0 ≤ dMin < dMax ≤ 1.");
        if (gridSize < 3)
            throw new ArgumentException("Grid size must be ≥ 3.", nameof(gridSize));
        if (series.Count < 50)
            throw new ArgumentException("Need at least 50 observations.", nameof(series));

        // Reference variance from full first-difference (d = dMax, near 1).
        double[] anchor = Difference(series, dMax);
        double anchorVar = ComputeVariance(anchor);
        if (anchorVar <= 0.0) return dMin;

        double step = (dMax - dMin) / (gridSize - 1);
        for (int g = 0; g < gridSize; g++)
        {
            double d = dMin + g * step;
            double[] differenced = Difference(series, d);
            double v = ComputeVariance(differenced);
            if (v > 0.0 && v / anchorVar <= varianceRatioCeiling)
            {
                return d;
            }
        }
        return dMax;
    }

    private static double ComputeVariance(double[] data)
    {
        double sum = 0.0;
        int count = 0;
        for (int i = 0; i < data.Length; i++)
        {
            if (double.IsNaN(data[i])) continue;
            sum += data[i];
            count++;
        }
        if (count < 2) return 0.0;
        double mean = sum / count;

        double sq = 0.0;
        for (int i = 0; i < data.Length; i++)
        {
            if (double.IsNaN(data[i])) continue;
            double dev = data[i] - mean;
            sq += dev * dev;
        }
        return sq / (count - 1);
    }
}
